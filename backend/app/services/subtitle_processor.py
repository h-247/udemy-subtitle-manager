def srt_to_vtt_text(srt_content: str) -> str:
    """
    Converts SubRip (.srt) subtitle format string to WebVTT (.vtt) format.
    Preserves all timestamps, cue ordering, and text content accurately.
    """
    # Standardize newlines
    normalized = srt_content.replace("\r\n", "\n").replace("\r", "\n").strip()
    if not normalized:
        return "WEBVTT\n\n"

    # Replace SRT comma in timestamps (00:01:20,000) with period (00:01:20.000)
    # Match patterns like "00:00:01,000 --> 00:00:04,000"
    vtt_timestamps = re.sub(
        r"(\d{2}:\d{2}:\d{2}),(\d{3})\s*-->\s*(\d{2}:\d{2}:\d{2}),(\d{3})",
        r"\1.\2 --> \3.\4",
        normalized,
    )

    # Prepend WEBVTT header if not already present
    if not vtt_timestamps.startswith("WEBVTT"):
        vtt_timestamps = "WEBVTT\n\n" + vtt_timestamps

    return vtt_timestamps


class SubtitleProcessor:
    @staticmethod
    def select_subtitle(
        available_captions: List[Dict[str, Any]],
        preferred_lang: str = "en",
    ) -> Tuple[Optional[Dict[str, Any]], str, Optional[str]]:
        """
        Selects subtitle based on specified priorities:
        1. Manually authored English (or requested language) subtitles.
        2. Auto-generated English (or requested language) subtitles.
        3. Other available subtitle if matching requested language.
        Never falsely labels auto-generated subtitles as manual.
        Returns: (caption_item, subtitle_type, language_code)
          subtitle_type is 'MANUAL', 'AUTO', 'NONE'
        """
        if not available_captions:
            return None, "NONE", None

        normalized_lang = preferred_lang.lower().split("-")[0].split("_")[0]

        manual_matches = []
        auto_matches = []

        for cap in available_captions:
            # Language code check
            cap_lang = (
                cap.get("locale_id")
                or cap.get("lang")
                or cap.get("language")
                or cap.get("language_code")
                or ""
            ).lower()

            cap_type = (cap.get("source") or cap.get("type") or "").lower()
            is_auto = (
                "auto" in cap_type
                or "generated" in cap_type
                or "automatic" in cap_type
                or "auto" in cap.get("label", "").lower()
                or "autogenerated" in cap.get("title", "").lower()
            )

            # Check matching language
            lang_base = cap_lang.split("-")[0].split("_")[0]
            if lang_base == normalized_lang or cap_lang == preferred_lang.lower():
                if is_auto:
                    auto_matches.append(cap)
                else:
                    manual_matches.append(cap)

        # 1. Prefer manual caption
        if manual_matches:
            best_manual = manual_matches[0]
            lang_code = (
                best_manual.get("locale_id")
                or best_manual.get("lang")
                or best_manual.get("language")
                or preferred_lang
            )
            return best_manual, "MANUAL", lang_code

        # 2. Fallback to auto-generated caption
        if auto_matches:
            best_auto = auto_matches[0]
            lang_code = (
                best_auto.get("locale_id")
                or best_auto.get("lang")
                or best_auto.get("language")
                or preferred_lang
            )
            return best_auto, "AUTO", lang_code

        # 3. If nothing matched preferred language, check if any other English exists
        if normalized_lang != "en":
            # If user requested Spanish but not found, fallback to English
            for cap in available_captions:
                cap_lang = (cap.get("locale_id") or cap.get("lang") or "").lower()
                if cap_lang.startswith("en"):
                    cap_type = (cap.get("source") or "").lower()
                    is_auto = "auto" in cap_type or "auto" in cap.get("label", "").lower()
                    stype = "AUTO" if is_auto else "MANUAL"
                    return cap, stype, cap_lang

        return None, "NONE", None

    @staticmethod
    def save_vtt_file(content: str, filename: str) -> str:
        """
        Saves subtitle content as UTF-8 .vtt file in temporary storage.
        Returns the absolute file path.
        """
        os.makedirs(settings.SUBTITLE_STORAGE_DIR, exist_ok=True)
        base_name = filename[:-4] if filename.lower().endswith(".vtt") else filename
        safe_base = sanitize_filename(base_name)
        safe_filename = f"{safe_base}.vtt"

        file_path = os.path.join(settings.SUBTITLE_STORAGE_DIR, safe_filename)

        # Clean / normalize WebVTT header
        clean_content = content.strip()
        if not clean_content.startswith("WEBVTT"):
            clean_content = "WEBVTT\n\n" + clean_content

        with open(file_path, "w", encoding="utf-8") as f:
            f.write(clean_content)

        return file_path

    @staticmethod
    def process_and_save_upload(raw_content: bytes, original_filename: str, target_filename: str) -> Tuple[str, str]:
        """
        Processes an uploaded .vtt or .srt file and saves it in temporary storage.
        Returns: (saved_file_path, 'IMPORTED')
        """
        os.makedirs(settings.SUBTITLE_STORAGE_DIR, exist_ok=True)
        text_content = raw_content.decode("utf-8", errors="replace")

        ext = os.path.splitext(original_filename)[1].lower()
        if ext == ".srt":
            vtt_content = srt_to_vtt_text(text_content)
        else:
            vtt_content = text_content
            if not vtt_content.strip().startswith("WEBVTT"):
                vtt_content = "WEBVTT\n\n" + vtt_content.strip()

        base_name = target_filename[:-4] if target_filename.lower().endswith(".vtt") else target_filename
        safe_base = sanitize_filename(base_name)
        safe_filename = f"{safe_base}.vtt"

        file_path = os.path.join(settings.SUBTITLE_STORAGE_DIR, safe_filename)
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(vtt_content)

        return file_path, "IMPORTED"


